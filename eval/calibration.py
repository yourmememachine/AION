"""Calibration log: independent scores recorded before discussion.

Standard library only. Each entry is one reviewer's independent score
for one subject, recorded as a probability in [0, 1] while the subject
is still blind. Once discussion is closed for a subject, no further
blind scores for it are accepted. Entries are immutable: a score can
never be edited, and an outcome can be attached exactly once, which
computes the signed error, absolute error and Brier score for that
entry. Summaries always carry the individual scores alongside any
aggregate, so dissent is never replaced by a mean. Entries are
hash-chained, persisted atomically, and validated on load; a corrupt
log fails closed and is never silently reset.

Limits, stated plainly: blindness is enforced only inside this log —
a score is accepted as blind until close_discussion is called, and
nothing here can detect discussion that happened outside the system
beforehand. Timestamps are generated by this log from the local clock
and are not externally anchored; there is no commit-and-reveal, so a
score's content is not committed before others are revealed. Ids are
plain strings: one entry per reviewer id does not prove the ids are
different people. Outcome fields and discussion stamps are sealed with
their own hashes (see _outcome_hash / _close_hash) so editing them on
disk is detected on load, subject to the same limit as every hash in
this project: a rewrite that also recomputes every hash is detectable
only against an externally anchored chain head. The per-reviewer
weight from reviewer_stats is advisory output; nothing in this module
applies it.
"""

from __future__ import annotations

import copy
import hashlib
import json
import math
import os
import re
import tempfile
from datetime import datetime, timezone
from pathlib import Path

SCHEMA_VERSION = 1
MAX_LOG_BYTES = 5 * 1024 * 1024
MAX_ENTRIES = 10000
MAX_TEXT = 2000
GENESIS_HASH = "0" * 64

_ID_RE = re.compile(r"[a-z0-9_-]{1,64}")


class CalibrationError(ValueError):
    """Raised when a calibration operation is not allowed."""


class CorruptCalibrationError(Exception):
    """Raised when the persisted calibration log cannot be trusted."""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _reject_constant(value: str):
    raise CorruptCalibrationError(f"non-finite number in log: {value}")


def _parse_float(text: str) -> float:
    value = float(text)
    if not math.isfinite(value):
        raise CorruptCalibrationError(f"non-finite number in log: {text}")
    return value


def _no_duplicate_keys(pairs):
    out = {}
    for key, value in pairs:
        if key in out:
            raise CorruptCalibrationError(
                f"duplicate key in log: {key}")
        out[key] = value
    return out


def _is_int(value) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _check_id(value, field: str) -> str:
    if not isinstance(value, str) or not _ID_RE.fullmatch(value):
        raise CalibrationError(f"{field} must match ^[a-z0-9_-]{{1,64}}$")
    return value


def _check_text(value, field: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise CalibrationError(f"{field} must be non-empty text")
    if len(value) > MAX_TEXT:
        raise CalibrationError(f"{field} exceeds {MAX_TEXT} characters")
    return value


def _check_probability(value, field: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise CalibrationError(f"{field} must be a number")
    try:
        out = float(value)
    except OverflowError as exc:
        raise CalibrationError(f"{field} must be finite") from exc
    if not math.isfinite(out) or not 0.0 <= out <= 1.0:
        raise CalibrationError(f"{field} must be a finite value in [0, 1]")
    return out


def _canonical(obj) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False).encode("utf-8")


_HASHED_KEYS = ("entry_id", "subject_id", "subject_ref", "reviewer_id",
                "score", "recorded_at", "phase", "prev_hash", "role")
ROLES = ("reviewer", "dissent")


def _entry_hash(entry: dict) -> str:
    # Only the immutable blind core is hashed: outcome fields and the
    # discussion stamp are filled in later and must not break the chain.
    # Keys are taken only when present, so entries written before the
    # role field existed keep their original hash.
    core = {k: entry[k] for k in _HASHED_KEYS if k in entry}
    return hashlib.sha256(_canonical(core)).hexdigest()


_ENTRY_KEYS = {
    "entry_id", "subject_id", "subject_ref", "reviewer_id", "score",
    "recorded_at", "phase", "discussion_started_at", "outcome",
    "outcome_at", "scored_at", "signed_error", "absolute_error", "brier",
    "prev_hash", "entry_hash", "outcome_hash", "close_hash",
}


def _outcome_hash(entry: dict) -> str:
    core = {k: entry.get(k) for k in
            ("entry_id", "outcome", "outcome_at", "scored_at",
             "signed_error", "absolute_error", "brier", "prev_hash")}
    return hashlib.sha256(_canonical(core)).hexdigest()


def _close_hash(entry: dict) -> str:
    core = {k: entry.get(k) for k in
            ("entry_id", "discussion_started_at", "prev_hash")}
    return hashlib.sha256(_canonical(core)).hexdigest()


def _closed_digest(closed: dict) -> str:
    return hashlib.sha256(_canonical(closed)).hexdigest()


def make_blind_entry(*, entry_id, subject_id, subject_ref, reviewer_id,
                     score, role="reviewer") -> dict:
    """Build one unscored blind entry. The timestamp is generated here.

    role is "reviewer" for a normal seat, or "dissent" for the seat
    assigned to argue against the proposal in this review — exactly one
    dissent seat is expected per subject, and the role is part of the
    hashed core so it cannot be reassigned after the fact.
    """
    if role not in ROLES:
        raise CalibrationError(f"role must be one of {ROLES}")
    return {
        "entry_id": _check_id(entry_id, "entry id"),
        "subject_id": _check_id(subject_id, "subject id"),
        "subject_ref": _check_text(subject_ref, "subject ref"),
        "reviewer_id": _check_id(reviewer_id, "reviewer id"),
        "role": role,
        "score": _check_probability(score, "score"),
        "recorded_at": _now(),
        "phase": "blind",
        "discussion_started_at": None,
        "outcome": None,
        "outcome_at": None,
        "scored_at": None,
        "signed_error": None,
        "absolute_error": None,
        "brier": None,
        "outcome_hash": None,
        "close_hash": None,
    }


def score_entry_against_outcome(entry, *, outcome, outcome_at=None) -> dict:
    """Return a new entry scored against a realised outcome. One-shot."""
    if not isinstance(entry, dict):
        raise CalibrationError("entry must be an object")
    if entry.get("outcome") is not None:
        raise CalibrationError("entry has already been scored")
    score = _check_probability(entry.get("score"), "entry score")
    outcome = _check_probability(outcome, "outcome")
    if outcome_at is not None and not isinstance(outcome_at, str):
        raise CalibrationError("outcome_at must be text")
    out = copy.deepcopy(entry)
    out["outcome"] = outcome
    out["outcome_at"] = outcome_at or _now()
    out["scored_at"] = _now()
    out["signed_error"] = score - outcome
    out["absolute_error"] = abs(score - outcome)
    out["brier"] = (score - outcome) ** 2
    out["outcome_hash"] = _outcome_hash(out)
    return out


def summarise_subject(entries) -> dict:
    """Aggregate for one subject, with every individual score preserved."""
    entries = list(entries)
    if not entries:
        raise CalibrationError("no entries to summarise")
    subject_ids = {e.get("subject_id") for e in entries}
    if len(subject_ids) != 1:
        raise CalibrationError("entries span more than one subject")
    pairs = sorted((e["reviewer_id"], float(e["score"])) for e in entries)
    values = [score for _, score in pairs]
    ordered = sorted(values)
    n = len(ordered)
    median = (ordered[n // 2] if n % 2
              else (ordered[n // 2 - 1] + ordered[n // 2]) / 2)
    return {
        "subject_id": subject_ids.pop(),
        "scores": tuple(pairs),
        "mean": sum(values) / n,
        "median": median,
        "min": ordered[0],
        "max": ordered[-1],
        "spread": ordered[-1] - ordered[0],
        "n": n,
    }


def minority_report(entries) -> dict:
    """Track the minority position on one subject, with its outcome.

    The minority is the set of reviewers whose score falls on the
    opposite side of 0.5 from the group's mean — the dissent that a
    consensus summary would hide. The report carries each dissenter's
    score and recording date, the assigned dissent seat's role, and,
    once the subject is scored, how accurate the minority turned out
    to be (their mean Brier score) next to the majority's.
    """
    entries = list(entries)
    if not entries:
        raise CalibrationError("no entries to report on")
    subject_ids = {e.get("subject_id") for e in entries}
    if len(subject_ids) != 1:
        raise CalibrationError("entries span more than one subject")
    mean = sum(float(e["score"]) for e in entries) / len(entries)
    if mean >= 0.5:
        minority = [e for e in entries if float(e["score"]) < 0.5]
        majority = [e for e in entries if float(e["score"]) >= 0.5]
    else:
        minority = [e for e in entries if float(e["score"]) > 0.5]
        majority = [e for e in entries if float(e["score"]) <= 0.5]

    def view(group):
        return tuple(sorted(
            ({"reviewer_id": e["reviewer_id"], "score": float(e["score"]),
              "recorded_at": e["recorded_at"],
              "role": e.get("role", "reviewer")} for e in group),
            key=lambda d: d["reviewer_id"]))

    def mean_brier(group):
        scored = [e for e in group if e.get("outcome") is not None]
        if not scored:
            return None
        return sum(e["brier"] for e in scored) / len(scored)

    outcomes = {e.get("outcome") for e in entries}
    return {
        "subject_id": subject_ids.pop(),
        "mean": mean,
        "minority": view(minority),
        "majority": view(majority),
        "dissent_seats": tuple(d["reviewer_id"] for d in view(entries)
                               if d["role"] == "dissent"),
        "outcome": outcomes.pop() if len(outcomes) == 1 else None,
        "minority_mean_brier": mean_brier(minority),
        "majority_mean_brier": mean_brier(majority),
    }


def reviewer_stats(entries) -> dict:
    """Per-reviewer calibration over scored entries only."""
    by_reviewer: dict = {}
    for entry in entries:
        if entry.get("outcome") is None:
            continue
        if entry.get("brier") is None or entry.get("absolute_error") is None:
            raise CalibrationError(
                "scored entry is missing its error fields")
        by_reviewer.setdefault(entry["reviewer_id"], []).append(entry)
    stats = {}
    for reviewer_id, scored in sorted(by_reviewer.items()):
        mean_abs = sum(e["absolute_error"] for e in scored) / len(scored)
        mean_brier = sum(e["brier"] for e in scored) / len(scored)
        stats[reviewer_id] = {
            "n_scored": len(scored),
            "mean_absolute_error": mean_abs,
            "mean_brier": mean_brier,
            "weight": 1.0 / (1.0 + mean_brier),
        }
    return stats


class CalibrationLog:
    """Append-and-score log persisted as one validated JSON document."""

    def __init__(self, log_dir):
        self.log_dir = Path(log_dir)
        self.log_dir.mkdir(parents=True, exist_ok=True)
        self.log_path = self.log_dir / "calibration.json"
        self._state = self._load()

    def _fresh(self) -> dict:
        return {"schema_version": SCHEMA_VERSION, "entries": [],
                "closed_subjects": {}, "closed_digest": _closed_digest({})}

    def _load(self) -> dict:
        if not self.log_path.exists():
            return self._fresh()
        if self.log_path.stat().st_size > MAX_LOG_BYTES:
            raise CorruptCalibrationError("log file exceeds size cap")
        raw = self.log_path.read_bytes()[: MAX_LOG_BYTES + 1]
        if len(raw) > MAX_LOG_BYTES:
            raise CorruptCalibrationError("log file exceeds size cap")
        try:
            data = json.loads(raw.decode("utf-8"),
                              parse_constant=_reject_constant,
                              parse_float=_parse_float,
                              object_pairs_hook=_no_duplicate_keys)
        except CorruptCalibrationError:
            raise
        except Exception as exc:
            self._quarantine(raw)
            raise CorruptCalibrationError(f"unreadable log: {exc}") from exc
        self._validate(data)
        return data

    def _quarantine(self, raw: bytes) -> None:
        stamp = datetime.now(timezone.utc).strftime("%Y%m%d%H%M%S%f")
        try:
            (self.log_dir / f"calibration.corrupt-{stamp}.json").write_bytes(raw)
        except OSError:
            pass

    def _validate(self, data) -> None:
        def bad(msg):
            raise CorruptCalibrationError(msg)

        if not isinstance(data, dict):
            bad("log is not an object")
        if not _is_int(data.get("schema_version")) or data["schema_version"] != SCHEMA_VERSION:
            bad("unsupported schema_version")
        entries, closed = data.get("entries"), data.get("closed_subjects")
        if not isinstance(entries, list) or not isinstance(closed, dict):
            bad("entries/closed_subjects have bad types")
        if len(entries) > MAX_ENTRIES:
            bad("entry cap exceeded")
        seen_pairs = set()
        prev_hash = GENESIS_HASH
        for entry in entries:
            if not isinstance(entry, dict) or set(entry.keys()) not in (
                    _ENTRY_KEYS, _ENTRY_KEYS | {"role"}):
                bad("entry has wrong keys")
            if "role" in entry and entry["role"] not in ROLES:
                bad("entry has an unknown role")
            try:
                _check_id(entry["entry_id"], "entry id")
                _check_id(entry["subject_id"], "subject id")
                _check_text(entry["subject_ref"], "subject ref")
                _check_id(entry["reviewer_id"], "reviewer id")
                _check_probability(entry["score"], "score")
            except CalibrationError as exc:
                bad(str(exc))
            if entry["phase"] != "blind":
                bad("entry phase is not blind")
            stamp = entry["discussion_started_at"]
            if stamp is not None and closed.get(entry["subject_id"]) != stamp:
                bad("discussion stamp does not match the closed record")
            pair = (entry["reviewer_id"], entry["subject_id"])
            if pair in seen_pairs:
                bad("duplicate reviewer/subject pair")
            seen_pairs.add(pair)
            scored = entry["outcome"] is not None
            for field in ("outcome", "outcome_at", "scored_at",
                          "signed_error", "absolute_error", "brier"):
                if scored != (entry[field] is not None):
                    bad("scored fields are inconsistent")
            if scored:
                try:
                    outcome = _check_probability(entry["outcome"], "outcome")
                except CalibrationError as exc:
                    bad(str(exc))
                score = float(entry["score"])
                if abs(entry["signed_error"] - (score - outcome)) > 1e-9:
                    bad("signed_error does not match score and outcome")
                if abs(entry["absolute_error"] - abs(score - outcome)) > 1e-9:
                    bad("absolute_error does not match")
                if abs(entry["brier"] - (score - outcome) ** 2) > 1e-9:
                    bad("brier does not match")
                if entry["outcome_hash"] != _outcome_hash(entry):
                    bad("outcome hash mismatch")
            elif entry["outcome_hash"] is not None:
                bad("unscored entry carries an outcome hash")
            if entry["discussion_started_at"] is not None:
                if entry["close_hash"] != _close_hash(entry):
                    bad("close hash mismatch")
            elif entry["close_hash"] is not None:
                bad("unclosed entry carries a close hash")
            if entry["prev_hash"] != prev_hash:
                bad("entry chain is broken")
            if entry["entry_hash"] != _entry_hash(entry):
                bad("entry hash mismatch")
            prev_hash = entry["entry_hash"]
        for subject_id, stamp in closed.items():
            try:
                _check_id(subject_id, "closed subject id")
            except CalibrationError as exc:
                bad(str(exc))
            if not isinstance(stamp, str) or not stamp:
                bad("bad discussion_started_at")
        if data.get("closed_digest") != _closed_digest(closed):
            bad("closed subjects digest mismatch")

    def save(self) -> None:
        self._state["closed_digest"] = _closed_digest(
            self._state["closed_subjects"])
        self._validate(self._state)
        payload = json.dumps(self._state, ensure_ascii=False, indent=2,
                             allow_nan=False).encode("utf-8")
        if len(payload) > MAX_LOG_BYTES:
            raise CalibrationError("log exceeds size cap")
        fd, tmp = tempfile.mkstemp(dir=self.log_dir,
                                   prefix=".calibration-", suffix=".tmp")
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(payload)
                fh.flush()
                os.fsync(fh.fileno())
            os.replace(tmp, self.log_path)
            dir_fd = os.open(self.log_dir, os.O_DIRECTORY)
            try:
                os.fsync(dir_fd)
            finally:
                os.close(dir_fd)
        except BaseException:
            try:
                os.unlink(tmp)
            except OSError:
                pass
            raise

    # -- operations ------------------------------------------------------

    def record_blind(self, entry) -> dict:
        """Record one blind entry. Rejected after discussion closes."""
        if not isinstance(entry, dict):
            raise CalibrationError("entry must be an object")
        candidate = {k: entry.get(k) for k in _ENTRY_KEYS
                     if k not in ("prev_hash", "entry_hash",
                                  "outcome_hash", "close_hash")}
        for key in ("entry_id", "subject_id", "subject_ref", "reviewer_id", "score"):
            if candidate.get(key) is None:
                raise CalibrationError(f"entry is missing {key}")
        _check_id(candidate["entry_id"], "entry id")
        _check_id(candidate["subject_id"], "subject id")
        _check_text(candidate["subject_ref"], "subject ref")
        _check_id(candidate["reviewer_id"], "reviewer id")
        _check_probability(candidate["score"], "score")
        role = entry.get("role", "reviewer")
        if role not in ROLES:
            raise CalibrationError(f"role must be one of {ROLES}")
        candidate["role"] = role
        if candidate.get("outcome") is not None:
            raise CalibrationError("a new entry cannot carry an outcome")
        subject_id = candidate["subject_id"]
        if subject_id in self._state["closed_subjects"]:
            raise CalibrationError(
                f"discussion already closed for subject: {subject_id}")
        for existing in self._state["entries"]:
            if existing["entry_id"] == candidate["entry_id"]:
                raise CalibrationError("duplicate entry id")
            if (existing["reviewer_id"] == candidate["reviewer_id"]
                    and existing["subject_id"] == subject_id):
                raise CalibrationError(
                    "duplicate blind score for reviewer and subject")
        if len(self._state["entries"]) >= MAX_ENTRIES:
            raise CalibrationError("entry cap reached")
        candidate["recorded_at"] = _now()
        candidate["phase"] = "blind"
        candidate["discussion_started_at"] = None
        for field in ("outcome", "outcome_at", "scored_at", "signed_error",
                      "absolute_error", "brier", "outcome_hash", "close_hash"):
            candidate[field] = None
        candidate["prev_hash"] = (self._state["entries"][-1]["entry_hash"]
                                  if self._state["entries"] else GENESIS_HASH)
        candidate["entry_hash"] = _entry_hash(candidate)
        snapshot = copy.deepcopy(self._state)
        try:
            self._state["entries"].append(candidate)
            self.save()
        except BaseException:
            self._state = snapshot
            raise
        return copy.deepcopy(candidate)

    def close_discussion(self, subject_id) -> None:
        _check_id(subject_id, "subject id")
        if subject_id in self._state["closed_subjects"]:
            raise CalibrationError(f"discussion already closed: {subject_id}")
        if not any(e["subject_id"] == subject_id for e in self._state["entries"]):
            raise CalibrationError(f"no blind entries for subject: {subject_id}")
        snapshot = copy.deepcopy(self._state)
        try:
            stamp = _now()
            self._state["closed_subjects"][subject_id] = stamp
            for entry in self._state["entries"]:
                if entry["subject_id"] == subject_id:
                    entry["discussion_started_at"] = stamp
                    entry["close_hash"] = _close_hash(entry)
            self.save()
        except BaseException:
            self._state = snapshot
            raise

    def record_outcome(self, entry_id, *, outcome) -> dict:
        _check_id(entry_id, "entry id")
        outcome = _check_probability(outcome, "outcome")
        snapshot = copy.deepcopy(self._state)
        try:
            for index, entry in enumerate(self._state["entries"]):
                if entry["entry_id"] == entry_id:
                    scored = score_entry_against_outcome(entry, outcome=outcome)
                    scored["prev_hash"] = entry["prev_hash"]
                    scored["entry_hash"] = _entry_hash(scored)
                    self._state["entries"][index] = scored
                    self.save()
                    return copy.deepcopy(scored)
            raise CalibrationError(f"unknown entry: {entry_id}")
        except BaseException:
            self._state = snapshot
            raise

    def record_outcome_for_subject(self, subject_id, *, outcome) -> tuple:
        """Score every entry of a subject in one atomic save."""
        _check_id(subject_id, "subject id")
        outcome = _check_probability(outcome, "outcome")
        targets = [e for e in self._state["entries"]
                   if e["subject_id"] == subject_id]
        if not targets:
            raise CalibrationError(f"no entries for subject: {subject_id}")
        if any(e["outcome"] is not None for e in targets):
            raise CalibrationError(f"subject already scored: {subject_id}")
        snapshot = copy.deepcopy(self._state)
        try:
            scored_entries = []
            for index, entry in enumerate(self._state["entries"]):
                if entry["subject_id"] != subject_id:
                    continue
                scored = score_entry_against_outcome(entry, outcome=outcome)
                scored["prev_hash"] = entry["prev_hash"]
                scored["entry_hash"] = _entry_hash(scored)
                self._state["entries"][index] = scored
                scored_entries.append(scored)
            self.save()
        except BaseException:
            self._state = snapshot
            raise
        return copy.deepcopy(tuple(scored_entries))

    def entries_for_subject(self, subject_id) -> tuple:
        _check_id(subject_id, "subject id")
        return copy.deepcopy(tuple(
            e for e in self._state["entries"] if e["subject_id"] == subject_id))

    def entries_for_reviewer(self, reviewer_id) -> tuple:
        _check_id(reviewer_id, "reviewer id")
        return copy.deepcopy(tuple(
            e for e in self._state["entries"] if e["reviewer_id"] == reviewer_id))
